export type SizeId = "reel" | "feed" | "story" | "pin";
export const SIZES: Record<SizeId, { width: number; height: number }> = {
  reel: { width: 1080, height: 1920 },
  story: { width: 1080, height: 1920 },
  feed: { width: 1080, height: 1350 },
  pin: { width: 1000, height: 1500 },
};

/**
 * Where text may sit so the platforms' own buttons and captions never cover it (TikTok and Reels:
 * the top bar, the right-hand buttons and the caption block at the bottom). Fractions of the frame.
 */
export const SAFE = { top: 0.12, bottom: 0.25, left: 0.074, right: 0.15 };

export interface Box {
  left: number;
  top: number;
  width: number;
  height: number;
}

/** The note's pill: plum ink at this opacity behind cotton text, so it reads on a white photo and a black one. */
export const NOTE_PILL_ALPHA = 0.68;
/** Never smaller than this at 1080 px wide (about 10 pt on a 390 pt phone). */
const NOTE_MIN_PX_AT_1080 = 28;

export interface NoteLayout {
  /** The most room the note may take (the pill is sized to its words and sits at `align` inside it). */
  box: Box;
  fontSize: number;
  align: "left" | "right";
  /** Text, labels and badges stay above this line so the note never covers them. */
  textBottom: number;
}

/**
 * Where the note goes on a frame of `size`, or null for a brand with no note. A reel (any size)
 * puts it in the bottom-left corner of the platforms' safe area (SAFE: clear of the caption block and
 * the right-hand buttons); a carousel slide (Instagram feed, no overlay) puts it in the bottom-right
 * corner, under the cover's Swipe pill. About 2.6–3.7% of the frame high, one line.
 */
export function photoNoteLayout(brand: Brand | undefined, size: { width: number; height: number }, kind: "reel" | "slide"): NoteLayout | null {
  if (!brand?.photoNote) return null;
  const { width, height } = size;
  const fontSize = Math.round(Math.max(height * 0.0155, (width * NOTE_MIN_PX_AT_1080) / 1080));
  const h = Math.round(fontSize * 1.8);
  const gap = Math.round(fontSize * 0.6);
  if (kind === "reel") {
    const bottom = height * (1 - SAFE.bottom);
    const box = { left: width * SAFE.left, top: bottom - h, width: width * (1 - SAFE.left - SAFE.right), height: h };
    return { box, fontSize, align: "left", textBottom: box.top - gap };
  }
  const margin = (56 * width) / 1080;
  const bottom = height - (28 * width) / 1080;
  const box = { left: margin, top: bottom - h, width: width - 2 * margin, height: h };
  return { box, fontSize, align: "right", textBottom: box.top - gap };
}

/** The lowest point a reel's text may reach: the safe area's bottom, lifted above the note when the brand has one. */
export function textBottom(brand: Brand | undefined, size: { width: number; height: number }): number {
  return photoNoteLayout(brand, size, "reel")?.textBottom ?? size.height * (1 - SAFE.bottom);
}
